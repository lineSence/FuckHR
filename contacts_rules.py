def lead_roles(*titles: str | None) -> tuple[str, ...]:
    """Кого искать в компании под эту вакансию. Первое совпадение выигрывает.

    Названия передаются по убыванию точности: сначала вакансия, потом запросы
    из профиля. Ничего не совпало — общий «руководитель отдела»: выдуманная
    специализация увела бы поиск в сторону сильнее, чем её отсутствие.
    """
    for title in titles:
        low = (title or "").lower()
        if not low:
            continue
        for needles, roles in LEAD_ROLE_HINTS:
            if any(needle in low for needle in needles):
                return roles
    return DEFAULT_LEAD_ROLES
