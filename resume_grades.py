"""Грейды в запросах поиска: словарь и распознавание притязаний (B-01).

Вынесено из `resume.py`: тот файл вплотную у потолка в 25 КБ [CORE-024], а
словарь грейдов — ровно та часть, которая будет расти: синонимы должностей
придумывают быстрее, чем меняются таблицы резюме. Для совместимости оба имени
продолжают быть доступны как `resume.GRADE_WORDS` и `resume.grade_claim`.
Сроки в месяцах — ожидания рынка, а не закон: они нужны только для
предупреждения владельцу и ничего не блокируют.
"""

from __future__ import annotations

import re

# Слово → ожидаемый стаж в месяцах.
GRADE_WORDS: dict[str, int] = {
    "lead": 60,
    "лид": 60,
    "тимлид": 60,
    "teamlead": 60,
    "руководитель": 60,
    "head": 72,
    "cto": 84,
    "senior": 48,
    "сеньор": 48,
    "ведущий": 48,
    "middle": 24,
    "миддл": 24,
}


def grade_claim(haystack: str) -> tuple[int, str]:
    """Самое требовательное слово грейда в тексте: (месяцы, слово).

    Сравниваем по границам слова, а не подстрокой. Подстрока здесь врёт дважды:
    «лид» сидит внутри «тимлид» и «валидация», «head» — внутри «overhead», и в
    предупреждение уходило чужое слово.

    Из нескольких совпадений берём самое требовательное: в запросе вида
    «middle/head of data» мягкий порог просто скрыл бы расхождение.
    """
    hits = [
        (need, len(word), word)
        for word, need in GRADE_WORDS.items()
        if re.search(r"(?<!\w)" + re.escape(word) + r"(?!\w)", haystack or "")
    ]
    if not hits:
        return 0, ""
    need, _, word = max(hits)
    return need, word


__all__ = ("GRADE_WORDS", "grade_claim")
